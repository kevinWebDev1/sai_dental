/**
 * Resolves clinic data by slug or dynamic query parameters.
 */
export function getClinicConfig(searchParams) {
  if (!searchParams) return CLINICS.sai;

  const key = (searchParams.get("c") || "").toLowerCase().trim();
  if (key && CLINICS[key]) {
    return CLINICS[key];
  }

  // Dynamic on-the-fly query fallback
  const customName = searchParams.get("name");
  if (customName) {
    const phone = searchParams.get("phone") || "919235179344";
    const doctor = searchParams.get("dr") || customName + " Team";
    const area = searchParams.get("area") || "Gomti Nagar, Lucknow";
    const rating = searchParams.get("rating") || "4.9";
    const reviews = searchParams.get("reviews") || "140+";

    return {
      slug: "custom",
      name: customName,
      brandTitle: customName.toUpperCase(),
      brandSubtitle: searchParams.get("sub") || "Specialized Dental Clinic",
      doctorName: doctor,
      phone: phone.replace(/[^0-9]/g, ""),
      phoneDisplay: phone,
      rating,
      reviews,
      area,
      address: searchParams.get("address") || `${area}, Lucknow, UP`,
      heroSubhead: `Comprehensive dental care, permanent implants, and gentle treatments in ${area}.`,
      hasMultipleBranches: false,
      heroButtons: [
        {
          label: `Book Consultation (${doctor})`,
          phone: phone.replace(/[^0-9]/g, ""),
          message: `Hello ${doctor}, I would like to schedule a consultation appointment.`,
        },
      ],
      doctors: [
        {
          num: "01",
          name: doctor,
          degrees: "B.D.S • M.D.S Specialists",
          role: "Senior Dental Surgeon & Implantologist",
          branch: area,
          branchShort: area.split(",")[0],
          photo: "/doctors/dr_rahul_tiwari.png",
          phoneRaw: phone,
          specialties: [
            "Painless Root Canal Treatments",
            "Dental Implants & Fixed Teeth",
            "Cosmetic Smile Design & Scaling",
          ],
          badgeColor: "bg-teal-50 text-teal-800 border-teal-200",
        },
      ],
      mapsEmbedUrl: `https://maps.google.com/maps?q=${encodeURIComponent(customName + " " + area)}&t=&z=15&ie=UTF8&iwloc=&output=embed`,
    };
  }

  return CLINICS.sai;
}
